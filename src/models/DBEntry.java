package src.models;

public class DBEntry {
    private String username;
    private int room;
    private int curr_line;
    private int last_line;

    public String getUsername() {
        return username;
    }

    public int getRoom() {
        return room;
    }

    public int getCurr_line() {
        return curr_line;
    }

    public int getLast_line() {
        return last_line;
    }
}
